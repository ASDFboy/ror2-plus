"""Builds src/Items/Complete/Lore.Generated.cs from lore_items.txt (keys = item class names)
and lore_voids.txt (keys = void IDs). Run: python3 -I tools/make_lore.py"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
def parse(fn):
    out, key, buf = {}, None, []
    for line in open(os.path.join(HERE, fn), encoding='utf-8').read().splitlines():
        m = re.match(r'^## (\S+)\s*$', line)
        if m:
            if key: out[key] = '\n'.join(buf).strip()
            key, buf = m.group(1), []
        else: buf.append(line)
    if key: out[key] = '\n'.join(buf).strip()
    return out
def cs(s): return '@"' + s.replace('"', '""') + '"'
items, voids = parse('lore_items.txt'), parse('lore_voids.txt')
body = ['// Generated by tools/make_lore.py. Edit the .txt files, not this.', 'using System.Collections.Generic;',
        'namespace ClassicItemsReturns.Items.Complete', '{', '    public static class Lore', '    {',
        '        public static string Item(string cls) => Items.TryGetValue(cls, out var s) ? s : "";',
        '        public static string Void(string id) => Voids.TryGetValue(id, out var s) ? s : "";',
        '        static readonly Dictionary<string, string> Items = new Dictionary<string, string> {']
body += [f'            {{ "{k}", {cs(v)} }},' for k, v in items.items()]
body += ['        };', '        static readonly Dictionary<string, string> Voids = new Dictionary<string, string> {']
body += [f'            {{ "{k}", {cs(v)} }},' for k, v in voids.items()]
body += ['        };', '    }', '}']
open(os.path.join(HERE, '..', 'src', 'Items', 'Complete', 'Lore.Generated.cs'), 'w', encoding='utf-8').write('\n'.join(body) + '\n')
print(len(items), 'items,', len(voids), 'voids')

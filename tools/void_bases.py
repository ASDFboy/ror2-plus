def nebula_mat():
    """Void 'starfield' surface like vanilla void items: deep indigo clouds with sparse bright stars. Emission-only, matte."""
    key = 'v_nebula'
    if key in bi._cache: return bi._cache[key]
    m = bpy.data.materials.new(key); m.use_nodes = True; m['alpha'] = 1.0
    N = m.node_tree.nodes; L = m.node_tree.links

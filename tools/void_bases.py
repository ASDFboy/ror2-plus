def corrupt(seed_s, tier):
    """Rework the original object the way vanilla void items do: keep its silhouette (already recoloured by VOIDMODE),
    turn its largest part into a starry nebula surface, and add a few hot-pink glowing veins and crystal shards."""
    r = random.Random(zlib.crc32(('corrupt' + seed_s).encode()))
    bpy.context.view_layer.update()
    deps = bpy.context.evaluated_depsgraph_get()
    meshes = [o for o in bpy.context.scene.objects if o.type in ('MESH', 'CURVE')]
    if not meshes: return
    # 1) nebula on the biggest non-glowing part (by bounding-box volume)
    def vol(o):
        d = o.dimensions; return d.x * d.y * d.z + 1e-6
    plain = [o for o in meshes if o.data.materials and not any(mm and mm.name.startswith('v_g') for mm in o.data.materials)]
    if plain:
        big = max(plain, key=vol)
        neb = nebula_mat()
        for i in range(len(big.data.materials)):
            if i == 0 or r.random() < 0.5: big.data.materials[i] = neb
    # sample surface points for accents
    pts = []
    for o in meshes:
        if o.type != 'MESH': continue
        eo = o.evaluated_get(deps); me = eo.to_mesh()
        step = max(1, len(me.vertices) // 80)
        for v in list(me.vertices)[::step]: pts.append((o.matrix_world @ v.co, (o.matrix_world.to_3x3() @ v.normal).normalized()))
        eo.to_mesh_clear()
    if not pts: return
    cen = sum((p for p, _ in pts), Vector()) / len(pts)
    front = [pn for pn in pts if pn[0].y < cen.y + 0.1] or pts
    glow = 'gpink'
    # 2) glowing veins across the surface (2-3)
    for _ in range(r.randint(2, 3)):
        p, nrm = r.choice(front); q, _n2 = r.choice(front)
        if (q - p).length < 0.3: continue
        path = [p + nrm * 0.03 + (q - p) * t + Vector((r.uniform(-.06, .06), -0.03, r.uniform(-.06, .06))) for t in (0, 0.3, 0.6, 1)]
        Tu([tuple(v) for v in path], 0.028, glow, taper=[0.4, 1, 0.8, 0.3])
    # 3) crystal shards growing out of the surface (1-2 clusters, more for higher tiers)
    for _ in range(r.randint(1, 1 + tier // 2)):
        p, nrm = r.choice(front)
        out = (nrm + (p - cen).normalized() * 0.5).normalized()
        for j in range(r.randint(2, 4)):
            d = (out + Vector((r.uniform(-.45, .45), r.uniform(-.2, .2), r.uniform(-.45, .45)))).normalized()
            h = r.uniform(0.25, 0.5) * (1.15 if j == 0 else 0.8)
            o = K(r.uniform(0.06, 0.11), 0.0, h, tuple(p + d * h * 0.42), m=r.choice(['vpale', 'vmid', 'gpurple']), v=5)
            o.rotation_euler = d.to_track_quat('Z', 'Y').to_euler()
    # 4) one curled void tendril on about half the items (no blobs on the tip)
    if r.random() < 0.5:
        p, nrm = r.choice(front); out = (nrm + (p - cen).normalized() * 0.6).normalized()
        side = out.cross(Vector((0, 1, 0))).normalized()
        path = [p - out * 0.03]
        for j in range(4):
            path.append(path[-1] + out * 0.17 + side * (0.12 * j))
        Tu([tuple(q) for q in path], 0.06, 'vshell', taper=[1, 0.75, 0.5, 0.3, 0.1])

